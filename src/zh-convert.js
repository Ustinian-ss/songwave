function buildMap() {
  const m = new Map();
  const a = Array.from(S2T_SIMPLE);
  const b = Array.from(S2T_TRAD);
  const n = Math.min(a.length, b.length);
  for (let i = 0; i < n; i++) {
    if (a[i] && b[i] && a[i] !== b[i]) m.set(a[i], b[i]);
  }
  return m;
}
const S2T_MAP = buildMap();

// 反向表（繁 -> 简）
const T2S_MAP = (() => {
  const m = new Map();
  S2T_MAP.forEach((t, s) => { if (!m.has(t)) m.set(t, s); });
  return m;
})();

function convert(text, dir = 's2t') {
  let s = String(text == null ? '' : text);
  if (!s) return '';
  // 1) 词组优先
  PHRASES.forEach(([simp, trad]) => {
    if (dir === 's2t') s = s.split(simp).join(trad);
    else s = s.split(trad).join(simp);
  });
  // 2) 逐字转换
  const map = dir === 's2t' ? S2T_MAP : T2S_MAP;
  let out = '';
  for (const ch of s) out += (map.get(ch) || ch);
  return out;
}

const toTraditional = (t) => convert(t, 's2t');
const toSimplified = (t) => convert(t, 't2s');

/** 表大小（便于测试与展示） */
function tableSize() { return { s2t: S2T_MAP.size, t2s: T2S_MAP.size, phrases: PHRASES.length }; }

